#!/usr/bin/env python3
"""Real local Git/tar fixtures for the pinned, offline Opus build boundary."""
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile
import unittest

spec = importlib.util.spec_from_file_location("opus_preparation", Path(__file__).with_name("prepare-opus.py"))
preparation = importlib.util.module_from_spec(spec)
spec.loader.exec_module(preparation)


def sha(data):
    return hashlib.sha256(data).hexdigest()


class OpusPreparationTests(unittest.TestCase):
    def fixture(self, root, malicious=None):
        upstream = root / "upstream"
        upstream.mkdir()
        contents = {
            "COPYING": b"Synthetic BSD notice retained unchanged\n",
            "opus_sources.mk": b"OPUS_SOURCES = src/opus.c\nOPUS_SOURCES_FLOAT = src/float.c\n",
            "celt_sources.mk": b"CELT_SOURCES = celt/celt.c\n",
            "silk_sources.mk": b"SILK_SOURCES = silk/silk.c\nSILK_SOURCES_FLOAT =\n",
            "src/opus.c": b"int synthetic_opus(void) { return 7; }\n",
            "src/float.c": b"int synthetic_float(void) { return 8; }\n",
            "celt/celt.c": b"int synthetic_celt(void) { return 9; }\n",
            "silk/silk.c": b"int synthetic_silk(void) { return 10; }\n",
            "include/opus.h": b"int synthetic_opus(void);\n",
            "celt/private.h": b"/* synthetic private header */\n",
            "configure": b"THIS UPSTREAM SCRIPT MUST NEVER EXECUTE\n",
        }
        archive = io.BytesIO()
        with tarfile.open(fileobj=archive, mode="w:gz") as tar:
            for name, payload in contents.items():
                item = tarfile.TarInfo("opus-9.8.7/" + name)
                item.size = len(payload)
                tar.addfile(item, io.BytesIO(payload))
            if malicious:
                item = tarfile.TarInfo(malicious[0])
                if malicious[1] == "link":
                    item.type = tarfile.SYMTYPE; item.linkname = "../../escape"
                    tar.addfile(item)
                else:
                    item.size = 1; tar.addfile(item, io.BytesIO(b"x"))
        blob = archive.getvalue()
        (upstream / "opus.tar.gz").write_bytes(blob)
        def git(*args):
            return subprocess.check_output(["git", "-C", str(upstream), *args], stderr=subprocess.DEVNULL).decode().strip()
        git("init", "--quiet")
        git("add", "opus.tar.gz")
        git("-c", "user.name=Opus Fixture", "-c", "user.email=synthetic@example.invalid", "commit", "--quiet", "-m", "fixture")
        # This literal manifest is an independently frozen preparation output,
        # never generated by production code for either side of the assertion.
        manifest = '''// swift-tools-version: 6.2
import PackageDescription
let package = Package(name: "MakoshOpus", platforms: [.macOS("26.0")],
    products: [.library(name: "COpus", targets: ["COpus"])],
    targets: [.target(name: "COpus", path: "Sources/COpus",
        sources: ["celt/celt.c", "silk/silk.c", "src/float.c", "src/opus.c"], publicHeadersPath: "include",
        cSettings: [.headerSearchPath("."), .headerSearchPath("celt"),
            .headerSearchPath("silk"), .headerSearchPath("silk/float"),
            .define("OPUS_BUILD"), .define("USE_ALLOCA"), .define("HAVE_ALLOCA_H"),
            .define("HAVE_LRINT"), .define("HAVE_LRINTF"),
            .define("PACKAGE_VERSION", to: "\\\"9.8.7\\\"")])], cLanguageStandard: .c99)
'''.encode()
        expected = {"Package.swift": manifest, "COPYING": contents["COPYING"]}
        for name, payload in contents.items():
            if name.endswith((".c", ".h")): expected["Sources/COpus/" + name] = payload
            elif name.endswith(".mk"): expected["Provenance/" + name] = payload
        expected_hashes = {name: sha(payload) for name, payload in expected.items()}
        lock = {"schemaVersion": 1, "sourceURL": str(upstream), "revision": git("rev-parse", "HEAD"),
            "tree": git("rev-parse", "HEAD^{tree}"), "archivePath": "opus.tar.gz", "archiveSHA256": sha(blob),
            "version": "9.8.7", "archiveRoot": "opus-9.8.7", "licenseSHA256": sha(contents["COPYING"]),
            "manifestSHA256": {name: sha(contents[name]) for name in ("opus_sources.mk", "celt_sources.mk", "silk_sources.mk")},
            "preparedFilesSHA256": sha(json.dumps(expected_hashes, sort_keys=True, separators=(",", ":")).encode())}
        lock_path = root / "lock.json"; lock_path.write_text(json.dumps(lock))
        return lock_path, root / "cache.git", root / "prepared", lock, expected

    # Missing pinned extraction or executing configure fails this real output test.
    def test_exact_committed_sources_and_notice_prepare_without_reference(self):
        with tempfile.TemporaryDirectory() as temporary:
            lock, cache, destination, _, expected = self.fixture(Path(temporary))
            preparation.prepare(lock, cache, destination)
            self.assertTrue(destination.is_dir(), "Pinned source preparation is missing")
            for name, payload in expected.items(): self.assertEqual((destination / name).read_bytes(), payload)
            self.assertFalse((destination / "configure").exists())
            self.assertFalse((destination.parent / ".references").exists())

    # A warm source-cache dependency or overwrite of authenticated output fails.
    def test_warm_reuse_requires_no_source_cache(self):
        with tempfile.TemporaryDirectory() as temporary:
            lock, cache, destination, _, _ = self.fixture(Path(temporary))
            preparation.prepare(lock, cache, destination)
            self.assertTrue(destination.is_dir(), "No offline artifact prepared")
            preparation.prepare(lock, destination.parent / "missing.git", destination)
            self.assertFalse((destination.parent / "missing.git").exists())

    # Trusting a rewritten marker instead of the tracked aggregate pin fails.
    def test_modified_extra_missing_and_symlink_outputs_are_refused(self):
        for mutation in ("modified", "extra", "missing", "symlink"):
            with self.subTest(mutation=mutation), tempfile.TemporaryDirectory() as temporary:
                lock, cache, destination, _, _ = self.fixture(Path(temporary))
                preparation.prepare(lock, cache, destination)
                self.assertTrue(destination.is_dir(), "No authenticated artifact prepared")
                file = destination / "Sources/COpus/src/opus.c"
                if mutation == "modified": file.write_bytes(b"changed")
                elif mutation == "extra": (destination / "extra.c").write_bytes(b"changed")
                elif mutation == "missing": file.unlink()
                else: file.unlink(); file.symlink_to(lock)
                with self.assertRaises(RuntimeError): preparation.prepare(lock, cache, destination)

    # Wrong Git tree/blob/license/manifest/file-set pins must never publish output.
    def test_each_changed_provenance_pin_fails_closed(self):
        for field in ("tree", "archiveSHA256", "licenseSHA256", "preparedFilesSHA256", "manifestSHA256"):
            with self.subTest(field=field), tempfile.TemporaryDirectory() as temporary:
                lock_path, cache, destination, lock, _ = self.fixture(Path(temporary))
                lock[field] = {name: "0" * 64 for name in lock[field]} if isinstance(lock[field], dict) else "0" * len(lock[field])
                lock_path.write_text(json.dumps(lock))
                with self.assertRaises(RuntimeError): preparation.prepare(lock_path, cache, destination)
                self.assertFalse(destination.exists())

    # Tar traversal, unexpected roots and symlinks must not escape staging.
    def test_unsafe_tar_members_never_publish_or_escape(self):
        for member in [("opus-9.8.7/../../escape", "file"), ("other/injected", "file"), ("opus-9.8.7/link", "link")]:
            with self.subTest(member=member), tempfile.TemporaryDirectory() as temporary:
                lock, cache, destination, _, _ = self.fixture(Path(temporary), member)
                with self.assertRaises(RuntimeError): preparation.prepare(lock, cache, destination)
                self.assertFalse(destination.exists()); self.assertFalse((Path(temporary) / "escape").exists())

    # An unmarked directory must be preserved, never overwritten with dependencies.
    def test_unmarked_and_symlink_destinations_are_preserved(self):
        for symlink in (False, True):
            with self.subTest(symlink=symlink), tempfile.TemporaryDirectory() as temporary:
                lock, cache, destination, _, _ = self.fixture(Path(temporary))
                preserved = destination.parent / "preserved"; preserved.mkdir()
                (preserved / "user.txt").write_bytes(b"keep")
                if symlink: destination.symlink_to(preserved, target_is_directory=True)
                else: destination.mkdir(); (destination / "user.txt").write_bytes(b"keep")
                with self.assertRaises(RuntimeError): preparation.prepare(lock, cache, destination)
                self.assertEqual((preserved / "user.txt").read_bytes(), b"keep")


if __name__ == "__main__": unittest.main()
